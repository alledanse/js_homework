// 1. “number” + 3 + 3
// “number” — рядок.
// “number” + 3 = "number3" (число 3 перетворюється на рядок)
// «number3» + 3 = "number33"
// Результат: "number33"

console.log('number' + 3 + 3);


// 2. null + 3
// Під час математичного додавання null перетворюється на число 0.
// 0 + 3 = 3
// Результат: 3

console.log(null + 3);


// 3. 5 && "qwerty"
// 5 це правдиве значення.
// Оператор && повертає друге значення, якщо перше правдиве.
// Результат: "qwerty"

console.log(5 && "qwerty");


// 4. +'40' + +'2' + "hillel"
// +'40' це 40
// +'2' це 2
// 40 + 2 =42
// 42 + "hillel" = "42hillel"
// Результат: "42hillel"

console.log(+'40' + +'2' + "hillel");


// 5. '10' - 5 === 6
// Оператор - перетворює рядок "10" в число 10.
// 10 - 5 = 5
// 5 === 6 це false
// Результат: false

console.log('10' - 5 === 6);


// 6. true + false
// true при математичних операціях перетворюється в 1
// false в 0
// 1 + 0 = 1
// Результат: 1

console.log(true + false);



// 7. '4px' - 3
// При використанні — рядок має бути повністю перетворений на число.
// '4px' не можна перетворити на число.
// Number('4px') це NaN
// NaN - 3 = NaN
// Результат: NaN

console.log('4px' - 3);


// 8. '4' - 3
// "4" перетворюється в число 4.
// 4 - 3 -> 1
// Результат: 1

console.log('4' - 3);



// 9. '6' + 3 ** 0
// Спочатку виконується піднесення до степеня:
// 3 ** 0 = 1
// '6' + 1 = "61"
// Результат: "61"

console.log('6' + 3 ** 0);


// 10. 12 / '6'
// Оператор / перетворює рядок "6" в число.
// 12 / 6 = 2
// Результат: 2

console.log(12 / '6');


// 11. '10' + (5 === 6)
// Спочатку виконується порівняння в дужках:
// 5 === 6 це false
// "10" + false -> "10false"
// Результат: "10false"


console.log('10' + (5 === 6));


// 12. null == ''
// При нестрогому порівнянні null == undefined має значения true,
// але null не дорівнює іншим значенням.
// null == '' - це false
// Результат: false

console.log(null == '');


// 13. 3 ** (9 / 3)
// Спочатку обчислюється вираз у дужках:
// 9 / 3 = 3
// 3 ** 3 = 27
// Результат: 27

console.log(3 ** (9 / 3));


// 14. !!'false' == !!'true'
// Будь-який непорожній рядок є правдивим значенням
// !!'false' -> true
// !!'true' -> true
// true == true -> true
// Результат: true

console.log(!!'false' == !!'true');


// 15. 0 || '0' && 1
// Спочатку виконується &&:
// '0' && 1 це 1, тому що "0" — непорожній рядок і є правдивим значенням
// 0 || 1 це 1
// Результат: 1

console.log(0 || '0' && 1);


// 16. (+null == false) < 1
// +null -> 0
// 0 == false -> true, оскільки false перетворюється на 0.
// true це 1 при порівнянні з числом.
// 1 < 1 це false
// Результат: false

console.log((+null == false) < 1);


// 17. false && true || true
// Спочатку виконується &&:
// false && true це false
// Потім ||:
// false || true це true
// Результат: true

console.log(false && true || true);


// 18. false && (false || true)
// Спочатку обчислюється вираз у дужках:
// false || true це true
// false && true це false
// Результат: false

console.log(false && (false || true));


// 19. (+null == false) < 1 ** 5
// Спочатку виконується піднесення до степеня:
// 1 ** 5 це 1
// +null це 0
// 0 == false це true
// true перетворюється на 1.
// 1 < 1 це false
// Результат: false

console.log((+null == false) < 1 ** 5);
